"""Regenerate paper/numbers.tex from paper/findings/results.csv.

Run from the repository root: .venv/bin/python paper/make_numbers.py

Every number in main.tex is a macro keyed by entry:dataset:arm:metric, a row of results.csv,
which in turn names the prereg entry that holds it. \\N{key} prints the value as stored,
\\Pct{key} as a percentage with one decimal, \\CI{key} the 95% interval. The script stops if
main.tex uses a key that results.csv does not have, so no number is typed by hand.
"""

import csv
import re
import sys
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

PAPER = Path(__file__).resolve().parent
ROWS = PAPER / "findings" / "results.csv"


def key(r: dict) -> str:
    return ":".join((r["entry"], r["dataset"], r["arm"], r["metric"]))


def pct(v: str) -> str:
    p = (Decimal(v) * 100).quantize(Decimal("0.1"), rounding=ROUND_HALF_UP)
    return f"{p:+}" if v.startswith("+") else str(p)


def tex(v: str) -> str:
    return "$-$" + v[1:] if v.startswith("-") else v


def main() -> None:
    rows = {key(r): r for r in csv.DictReader(ROWS.open())}
    used = set(re.findall(r"\\(?:N|Pct|CI)\{([^}]+)\}", (PAPER / "main.tex").read_text()))
    missing = sorted(used - rows.keys())
    if missing:
        sys.exit("results.csv has no row for: " + ", ".join(missing))
    out = [
        "% Generated by make_numbers.py from findings/results.csv; do not edit.",
        r"\newcommand{\N}[1]{\csname n@#1\endcsname}",
        r"\newcommand{\Pct}[1]{\csname p@#1\endcsname}",
        r"\newcommand{\CI}[1]{\csname c@#1\endcsname}",
    ]
    for k in sorted(used):
        r = rows[k]
        out.append(rf"\expandafter\def\csname n@{k}\endcsname{{{tex(r['value'])}}}")
        out.append(rf"\expandafter\def\csname p@{k}\endcsname{{{tex(pct(r['value']))}}}")
        if r["ci_low"]:
            lo, hi = tex(r["ci_low"]), tex(r["ci_high"])
            out.append(rf"\expandafter\def\csname c@{k}\endcsname{{[{lo}, {hi}]}}")
    (PAPER / "numbers.tex").write_text("\n".join(out) + "\n")
    print(f"numbers.tex: {len(used)} keys")


if __name__ == "__main__":
    main()
